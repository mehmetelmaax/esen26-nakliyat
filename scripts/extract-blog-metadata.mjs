import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const blogDataPath = path.join(__dirname, '..', 'src', 'lib', 'blog-data.ts');
const outputPath = path.join(__dirname, '..', 'src', 'lib', 'blog-metadata.ts');

function cleanTs(content) {
  // Strip TypeScript types to import as ES module in Node
  return content
    .replace(/export interface[\s\S]*?\n}/g, '')
    .replace(/:\s*Record<[\s\S]*?>/g, '')
    .replace(/:\s*BlogPostData/g, '')
    .replace(/as const/g, '');
}

async function extract() {
  const content = fs.readFileSync(blogDataPath, 'utf8');
  const cleanCode = cleanTs(content);
  
  const tempPath = path.join(__dirname, 'temp-blog-data.mjs');
  fs.writeFileSync(tempPath, cleanCode, 'utf8');

  try {
    const { blogDatabase } = await import('./temp-blog-data.mjs');
    const metadata = {};
    
    Object.keys(blogDatabase).forEach(key => {
      const post = blogDatabase[key];
      const text = post.contentHtml.replace(/<[^>]*>/g, '');
      const words = text.trim().split(/\s+/).length;
      const readingTime = Math.max(1, Math.ceil(words / 200));
      
      metadata[key] = {
        id: post.id,
        title: post.title,
        desc: post.desc,
        excerpt: post.excerpt,
        date: post.date,
        author: post.author,
        image: post.image,
        category: post.category,
        readingTime
      };
    });

    const outputContent = `// Automatically generated by scripts/extract-blog-metadata.mjs
export interface SimplifiedBlogPost {
  id: string;
  title: string;
  desc: string;
  excerpt: string;
  date: string;
  author: string;
  image: string;
  category: 'Fiyat' | 'Rehber' | 'Yasal' | 'Teknik' | 'Bölge';
  readingTime: number;
}

export const blogMetadata: Record<string, SimplifiedBlogPost> = ${JSON.stringify(metadata, null, 2)};
`;

    fs.writeFileSync(outputPath, outputContent, 'utf8');
    console.log('✅ Successfully extracted blog metadata to src/lib/blog-metadata.ts');
  } catch (err) {
    console.error('❌ Error during extraction:', err);
  } finally {
    if (fs.existsSync(tempPath)) {
      fs.unlinkSync(tempPath);
    }
  }
}

extract();
